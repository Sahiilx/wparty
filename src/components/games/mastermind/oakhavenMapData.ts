// ----------------------------------------------------------------------------
// Helper: Find what recipes can be made with a given item
// ----------------------------------------------------------------------------
export function getRecipesUsingItem(itemId: MastermindItem): ItemDetail[] {
  return Object.values(MASTER_ITEM_CATALOG).filter(
    (item) => item.components && item.components.includes(itemId)
  );
}

